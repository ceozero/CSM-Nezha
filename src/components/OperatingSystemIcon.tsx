/** 按 CFSM 返回的系统名称展示已打包的发行版图标，不依赖访客网络访问外部资源。 */
export default function OperatingSystemIcon({
	platform,
	className,
}: {
	platform: string;
	className?: string;
}) {
	const osName = GetOsName(platform);
	const iconSlug = getOsIconSlug(platform);
	const iconPath = OS_ICON_PATHS[iconSlug];

	if (iconSlug === "windows") {
		return (
			<MageMicrosoftWindows
				aria-label={`${osName} 系统图标`}
				className={cn("size-3 shrink-0 text-rose-500", className)}
				role="img"
			/>
		);
	}

	if (!iconPath) {
		return (
			<MonitorCog
				aria-label={`${osName} 系统图标`}
				className={cn("size-3 text-rose-500", className)}
				role="img"
			/>
		);
	}

	return (
		<svg
			aria-label={`${osName} 系统图标`}
			className={cn("size-3 shrink-0 text-rose-500", className)}
			fill="currentColor"
			role="img"
			viewBox="0 0 24 24"
		>
			<path d={iconPath} />
		</svg>
	);
}
